export const KO_STYLE = `[글 다듬기 — 한글 AI 티 없이]
위 형식 규칙(JSON 모양 · 번호 · 글머리 · 길이 · 말투)이 먼저다. 그 안의 문장은 사람이 말하듯 쓴다.
- 번역투를 쓰지 않는다: "~에 있어서" → "~에서", "~를 가지고 있다" → "~가 있다", "~되어지다" → "~되다", "~에 의해" → 하는 사람을 주어로. "~를 통해"를 몰아 쓰지 않는다.
- AI 관용구를 쓰지 않는다: 결론적으로 · 요약하자면 · 시사하는 바가 크다 · 주목할 만하다 · 다음과 같다 · 단순한 ~을 넘어 · 지금이 바로 ~할 때.
- "A가 아니라 B" 같은 대구는 한 번까지만. 셋씩 맞춘 나열을 버릇처럼 쓰지 않는다.
- 연결어미 뒤에 쉼표를 찍지 않는다("배우고, 쉬고" → "배우고 쉬고").
- 줄표(—, –)를 쓰지 않는다. 쉼표나 두 문장으로 나누고, 범위는 "10~15분"처럼 쓴다.
- 같은 끝맺음을 네 번 넘게 잇지 않고, 짧은 문장과 긴 문장을 섞는다.
- 숫자 · 이름 · 인용은 그대로 두고, "~해야 해요" · "~일 수 있어요"의 뜻(당위 · 추측)은 바꾸지 않는다.`;

/** 보이지 않는 문자 — 소프트하이픈 · 아랍 글자 표시 · 몽골 모음 구분 · 제로폭(공백 · 비결합) · 방향 표시/제어 · 단어 잇기 · BOM.
 *  U+200D(이모지 잇기)는 일부러 뺐다. */
const INVISIBLE = /[­؜᠎​‌‎‏‪-‮⁠-⁤⁦-⁩﻿]/g;
/** 태그 문자(U+E0000 ~ U+E007F) — 본문에 안 보이는 글을 숨길 때만 쓰인다 */
const TAG_CHARS = /[\u{E0000}-\u{E007F}]/gu;
/** 특수 공백 → 보통 공백 */
const ODD_SPACE = /[      ]/g;

/** 보이지 않는 문자 청소 — 보이는 글자는 그대로 */
export function cleanKo(text: string): string {
  if (!text) return text;
  return text.replace(INVISIBLE, "").replace(TAG_CHARS, "").replace(ODD_SPACE, " ");
}

/** 자동으로 찾는 S1 지문(153 앱 규칙 「한글 AI 티 지문」과 같은 낱말) — 걸린 것만 돌려준다 */
const TELL_WORDS = ["—", "–", "결론적으로", "요약하자면", "정리하자면", "시사하는 바", "주목할 만", "주목할 점은", "되어지", "되어진", "다음과 같", "에 대해 알아보", "에 대해서 알아보", "시간을 가졌", "보여질 수"] as const;
const TELL_RES: Array<[string, RegExp]> = [
  ["단순한 ~을 넘어", /단순(한|히) [^\n.!?]{1,20}넘어/],
  ["겹 완곡", /수 있을 것으로 (보|예상|기대|판단)/],
  ["지금이 바로 ~할 때", /(지금|이제)[^\n.!?]{0,15}(할|될) (때|시점)(입니다|이에요|예요)/],
];

export function koTells(text: string): string[] {
  const t = text ?? "";
  const found: string[] = [];
  for (const w of TELL_WORDS) if (t.includes(w)) found.push(w);
  for (const [name, re] of TELL_RES) if (re.test(t)) found.push(name);
  if (cleanKo(t) !== t) found.push("보이지 않는 문자");
  return found;
}
