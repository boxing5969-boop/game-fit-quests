// ── 홀딩(일시정지) 규칙 — 회원 이용계약서 제3조와 같은 표. 153OS 셀프 홀딩(app_hold_policy)도 같은 표를 쓴다.
//    바꾸면 아래 약관 문구·osamiFaq(mb-hold)·153OS 마이그레이션까지 함께.
export interface HoldTier {
  maxCount: number;   // 홀딩 가능 횟수
  maxDays: number;    // 합계 최대 일수
  perHold: number;    // 1회 최대 일수
}
/** 계약 개월수 → 홀딩 자격. 1~2개월 불가 · 3~4개월 1회 15일 · 5~11개월 2회 합계 30일 · 12개월 이상 3회 합계 60일.
 *  1회 최대는 3~4개월 15일, 5개월 이상 30일 — 합계 안에서 몰아 쓰거나 나눠 쓸 수 있다. */
export function holdPolicy(months: number): HoldTier {
  if (months >= 12) return { maxCount: 3, maxDays: 60, perHold: 30 };
  if (months >= 5) return { maxCount: 2, maxDays: 30, perHold: 30 };
  if (months >= 3) return { maxCount: 1, maxDays: 15, perHold: 15 };
  return { maxCount: 0, maxDays: 0, perHold: 0 };
}
