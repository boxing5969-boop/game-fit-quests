export interface GrowthDirection {
  title: string;
  body: string;
}

export interface GrowthSource {
  /** 출처 이름 — 화면에 그대로 */
  name: string;
  /** 원문 주소 — 있으면 누르면 열린다 */
  url?: string;
}

export interface GrowthLesson {
  id: string;
  /** 보이기 시작하는 날 (KST, YYYY-MM-DD) */
  from: string;
  /** 주제 — 카드 작은 글 (날마다 글은 요일 코너 이름) */
  theme: string;
  /** 큰 제목 */
  title: string;
  /** 카드 한 줄 */
  hook: string;
  /** 1분 이야기 (문단) */
  story: string[];
  /** 오늘의 방향 — 오늘 해 볼 것 (날마다 글은 하나) */
  directions: GrowthDirection[];
  /** 마무리 한 줄 */
  pledge: string;
  /** '오늘의 글'로 보이는 날 수 — 날마다 글은 1 (없으면 NEWEST_LESSON_DAYS) */
  days?: number;
  /** 출처 — 원문을 열어 확인한 것만 */
  sources?: GrowthSource[];
}

