/** 상세 주소 — /handwrap?step=N (1부터, 마지막 = 완성) */
export const handWrapStepParam = (raw: string | null): number | null => {
  if (!raw) return null;
  const n = Number(raw);
  return Number.isInteger(n) && n >= 1 && n <= HANDWRAP_STEPS.length ? n - 1 : null;
};
