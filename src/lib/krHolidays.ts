/** 표가 있는 해 — 이 밖의 해는 공휴일을 모른다(빨간 글씨 없음) */
export const KR_HOLIDAY_YEARS = [2026, 2027, 2028] as const;

/** 그날 공휴일 이름 (없으면 null) */
export const holidayOn = (date: string): string | null => H[date] ?? null;

export const isHoliday = (date: string): boolean => date in H;

/** from ~ to 안의 공휴일 [날짜, 이름] (날짜 순) */
export const holidaysBetween = (from: string, to: string): Array<[string, string]> =>
  Object.entries(H)
    .filter(([d]) => d >= from && d <= to)
    .sort(([a], [b]) => a.localeCompare(b));
