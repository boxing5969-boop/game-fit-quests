/**
 * 소리로 읽을 글 다듬기 — 휴대폰 음성(TTS) · 녹음 대본 공통.
 *
 * 정식 명칭은 '일오삼 복싱짐'이다 (2026-10-19 대표님: "백오삼 복싱짐이 아니라 일오삼 복싱짐이 우리 정식 명칭").
 * 휴대폰 음성은 '153'을 숫자로 보고 '백오십삼'이라 읽어 버리므로, 소리로 내보내는 글은 반드시 이 함수를 거친다.
 * 화면 글(자막 · 제목)은 '153' 그대로 둔다.
 *
 *   · 앞뒤가 숫자가 아닌 '153'만 바꾼다 — 1530 · 2153 같은 다른 숫자는 그대로.
 *   · 정규식 뒤돌아보기(lookbehind)는 구형 아이폰 사파리에서 문법 오류로 화면이 안 뜨므로 쓰지 않고,
 *     앞 글자를 붙잡았다가 그대로 돌려놓는다.
 */
const BRAND_153 = /(^|[^0-9])153(?![0-9])/g;

export function toSpokenKo(text: string): string {
  return text.replace(BRAND_153, "$1일오삼");
}
