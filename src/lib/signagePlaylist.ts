/**
 * 사이니지 3번 화면(/tv/{지점}/3)에 돌아가는 안내 이미지 목록.
 *
 * 1·2번 화면은 실시간 보드(지금 운동 중 · 오늘 방문 명단)다.
 * 3번은 회원에게 "제도를 설명하는" 화면이라 실시간 데이터를 쓰지 않는다.
 * 그래서 Supabase 를 보지 않고 앱에 같이 배포된 이미지만 돌린다 —
 * 통신이 끊겨도, DB 가 멈춰도 TV 는 계속 돌아야 하기 때문이다.
 *
 * ── 이미지 바꾸는 방법 ────────────────────────────────────────
 *   1) 1920×1080 PNG 을 public/signage/ 에 넣는다.
 *      파일명은 영문·숫자만 — 한글 파일명을 못 읽는 사이니지 브라우저 기종이 있다.
 *   2) 아래 배열에 한 줄 추가하거나 순서를 바꾼다.
 *   3) bun run push
 *
 * ── 왜 8초인가 ────────────────────────────────────────────────
 *   50인치를 2~4m 에서 지나가며 한 장을 다 읽는 데 7~8초가 걸린다.
 *   8장 × 8초 = 약 1분 한 바퀴. 10장을 넘기면 한 바퀴를 못 보고 지나가서
 *   매번 다른 조각만 보고 기준을 오해하게 된다.
 */

