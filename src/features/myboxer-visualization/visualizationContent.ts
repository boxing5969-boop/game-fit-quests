/** 오늘의 추천 — 시간대 · 지금 기분 · 153 PB 기록 */
export function recommendSession(opts: { hour: number; hasPb: boolean; doneToday: boolean; lastIds: string[] }): MindSession {
  const pick = (id: string) => getMindSession(id) ?? MIND_SESSIONS[0];
  const { hour, hasPb, doneToday, lastIds } = opts;
  if (hour >= 22 || hour < 5) return pick(doneToday ? "breath-box" : "recover-cooldown");
  if (doneToday) return pick(lastIds.includes("skill-one-two") ? "recover-cooldown" : "skill-one-two");
  if (hasPb && !lastIds.slice(0, 5).includes("pb-rehearsal") && new Date().getDay() % 3 === 0) return pick("pb-rehearsal");
  return pick("myboxer-153-returned-person");
}
