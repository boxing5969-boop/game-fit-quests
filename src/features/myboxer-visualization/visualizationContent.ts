  /** 대략 몇 분 */
  minutes: number;
  /** 시작 화면 설명 */
  intro: string;
  /** 이렇게 하면 좋아요 */
  tips: string[];
  /** 왜 효과가 있나요 (근거 한 줄) */
  why: string;
  soundscape: Soundscape;
  /** 카드 색 (그라디언트 두 색) */
  tint: [string, string];
  cues: Cue[];
